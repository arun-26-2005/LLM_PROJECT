"""
orchestration/state.py
----------------------
Pipeline state definition for the LangGraph agent orchestration.

Defines the TypedDict that flows through every node in the LangGraph
state machine. Each node reads from and writes to this shared state.

Architecture Role:
    The PipelineState is the single source of truth during a pipeline run.
    It accumulates data as it flows through:
    validate_intake → retrieve_clauses → call_policy_api → call_hospital_api →
    apply_rules_engine → llm_reasoning → citation_guard → escalation_gate →
    format_recommendation → log_audit_record

Usage:
    from orchestration.state import PipelineState
"""

from __future__ import annotations

from typing import Any, Optional
from typing_extensions import TypedDict


class PipelineState(TypedDict, total=False):
    """Shared state object passed through the LangGraph pipeline.

    All fields are optional (total=False) because each node populates
    its own outputs incrementally.

    Sections:
        - Input: Raw intake result from Member 1's pipeline.
        - Retrieval: Clauses retrieved from the vector store.
        - Tool Calls: Responses from mock core system APIs.
        - Rules Engine: Deterministic adjudication output.
        - LLM Reasoning: Natural-language reasoning with citations.
        - Final Output: Recommendation and audit record.
        - Metrics: Latency, cost, and quality tracking.
    """

    # ── Input ──────────────────────────────────────────────────────────
    intake_result: dict[str, Any]
    """Serialized IntakeResult from Member 1's extraction pipeline."""

    pre_auth_request: dict[str, Any]
    """Serialized PreAuthRequest extracted from the intake result."""

    # ── Retrieval ──────────────────────────────────────────────────────
    retrieval_query: str
    """Composite query string built from diagnosis + procedure + plan type."""

    retrieved_clauses: list[dict[str, Any]]
    """List of RetrievedClause objects (serialized as dicts)."""

    # ── Tool Call Results ──────────────────────────────────────────────
    policy_status: dict[str, Any]
    """Response from GET /api/policy/{id}/status."""

    waiting_period_info: dict[str, Any]
    """Response from GET /api/policy/{id}/waiting-period."""

    sub_limit_balance: dict[str, Any]
    """Response from GET /api/policy/{id}/sub-limit-balance."""

    hospital_empanelment: dict[str, Any]
    """Response from GET /api/hospital/{id}/empanelment."""

    # ── Rules Engine Output ────────────────────────────────────────────
    adjudication_result: dict[str, Any]
    """Serialized AdjudicationResult from the rules engine."""

    # ── LLM Reasoning ─────────────────────────────────────────────────
    reasoning_narrative: str
    """Natural-language reasoning generated by the LLM."""

    raw_llm_output: str
    """Raw LLM output before citation guard processing."""

    hallucinated_citations: list[str]
    """Citations found in LLM output that don't match retrieved clauses."""

    # ── Final Output ──────────────────────────────────────────────────
    recommendation: str
    """Final recommendation: RECOMMEND_AUTHORISE / RECOMMEND_QUERY / RECOMMEND_DENY."""

    confidence: float
    """Final confidence score (0.0–1.0)."""

    escalation_triggers: list[str]
    """Reasons for escalation to human review (Guardrail #7)."""

    needs_escalation: bool
    """Whether this case requires human review."""

    decision_record: dict[str, Any]
    """Final decision record for the audit log (shared with Member 3)."""

    # ── Metrics Tracking ──────────────────────────────────────────────
    node_latencies: dict[str, float]
    """Wall-clock time (seconds) for each pipeline node."""

    total_latency: float
    """End-to-end pipeline latency in seconds."""

    llm_token_count: dict[str, int]
    """Token usage: {"input_tokens": N, "output_tokens": N}."""

    llm_cost_inr: float
    """Estimated LLM cost in INR for this transaction."""

    # ── Error Handling ────────────────────────────────────────────────
    errors: list[str]
    """Errors encountered during pipeline execution."""

    pipeline_status: str
    """Overall pipeline status: "running", "completed", "failed", "escalated"."""

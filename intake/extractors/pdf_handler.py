"""
intake/extractors/pdf_handler.py
--------------------------------
Handler for Digital PDF documents.
Extracts embedded text using pypdf. If the PDF contains no extractable text
(scanned container), it automatically routes to the OCR handler.
"""

from __future__ import annotations

from pathlib import Path
from typing import Union

# pyrefly: ignore [missing-import]
from pypdf import PdfReader

# pyrefly: ignore [missing-import]
from schemas import SourceFormat
from intake.models import IntakeResult
from intake.structured_extractor import extract_structured_pre_auth


def process_digital_pdf_intake(source_path: Union[str, Path]) -> IntakeResult:
    """
    Extract text from a digital PDF file and route to structured extractor.

    Inspects digital text streams across all document pages using pypdf.
    If the document is a scanned image wrapped in a PDF envelope (i.e. contains
    fewer than 20 characters of extractable text), it automatically delegates
    processing to the OCR handler.

    Args:
        source_path (Union[str, Path]): Path to the digital PDF file on disk.

    Returns:
        IntakeResult: Unified intake result containing the extracted PreAuthRequest
            (if successful), confidence score, extraction metadata, and validation errors.

    Example:
        >>> result = process_digital_pdf_intake("data/sample_request.pdf")
        >>> if result.is_success:
        ...     print(f"Patient: {result.request.patient.name}")
    """
    # =========================================================================
    # 1. Input Validation & Existence Check
    # =========================================================================
    path = Path(source_path)

    # Fail fast before initializing PDF parsing overhead to provide clear diagnostic
    # feedback if the target path is missing or points to a non-file entity.
    if not path.is_file():
        return IntakeResult(
            request=None,
            is_success=False,
            source_format=SourceFormat.PDF,
            summary=f"File not found: {path}",
            confidence_score=0.0,
            validation_errors=[f"PDF file does not exist at '{path}'."],
        )

    try:
        # =====================================================================
        # 2. Digital Text Extraction
        # =====================================================================
        # Casting path to string ensures compatibility across varied pypdf versions
        # that may expect a standard string path rather than a Pathlib object.
        reader = PdfReader(str(path))
        extracted_text_list: list[str] = []

        # Accumulate text page-by-page in a list to prevent repetitive string
        # reallocation overhead on multi-page clinical records.
        for i, page in enumerate(reader.pages):
            page_text = page.extract_text()
            # Filter out blank or whitespace-only pages to keep the text buffer dense
            if page_text:
                extracted_text_list.append(page_text)

        full_text = "\n".join(extracted_text_list).strip()

        # =====================================================================
        # 3. Scanned PDF Fallback Detection
        # =====================================================================
        # Documents generated by desktop scanners often wrap raw raster images
        # inside a PDF container without optical character streams. If fewer than 20
        # characters are recovered, the document cannot be processed digitally;
        # route to the OCR pipeline to unpack and transcribe embedded image pages.
        if not full_text or len(full_text) < 20:
            # Lazy import avoids circular dependency cycles between pdf_handler and ocr_handler
            from intake.extractors.ocr_handler import process_ocr_intake
            return process_ocr_intake(path, source_format=SourceFormat.PDF)

        # =====================================================================
        # 4. Structured Extraction Pipeline Routing
        # =====================================================================
        # Native digital PDFs possess 100% character fidelity; pass ocr_confidence=None
        # because character extraction did not undergo optical statistical inference.
        return extract_structured_pre_auth(
            raw_text=full_text,
            source_format=SourceFormat.PDF,
            ocr_confidence=None,
        )

    except Exception as exc:
        # =====================================================================
        # 5. Exception Handling & Graceful Degradation
        # =====================================================================
        # Catch low-level parsing issues (e.g. malformed cross-reference tables,
        # unsupported encryption filters, or truncated streams) to ensure the
        # pipeline returns a standardized failed result instead of raising an unhandled crash.
        err_msg = str(exc)
        return IntakeResult(
            request=None,
            is_success=False,
            source_format=SourceFormat.PDF,
            summary=f"Failed to read digital PDF: {err_msg}",
            confidence_score=0.0,
            validation_errors=[err_msg],
        )
